import React, { useState } from 'react';
import { generateAiDescription } from '../api';

export default function TaskForm({ onTaskCreated, loading }) {
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [priority, setPriority] = useState('medium');
  const [isAiGenerated, setIsAiGenerated] = useState(false);
  const [aiLoading, setAiLoading] = useState(false);
  const [aiMessage, setAiMessage] = useState(null);

  const handleGenerateAi = async () => {
    if (!title.trim() || title.trim().length < 3) {
      setAiMessage({
        type: 'warning',
        text: 'Please enter a task title (at least 3 characters) before generating description.'
      });
      return;
    }

    try {
      setAiLoading(true);
      setAiMessage(null);

      const result = await generateAiDescription(title.trim());

      if (result.fallback) {
        setAiMessage({
          type: 'warning',
          text: result.message || 'AI service unavailable. You can enter the description manually below.'
        });
      } else if (result.description) {
        setDescription(result.description);
        setIsAiGenerated(true);
        setAiMessage({
          type: 'success',
          text: '✨ Description auto-generated! Please review, edit, or adjust it before saving.'
        });
      }
    } catch (err) {
      setAiMessage({
        type: 'warning',
        text: err.message || 'Failed to connect to AI generation endpoint.'
      });
    } finally {
      setAiLoading(false);
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    if (!title.trim()) return;

    onTaskCreated({
      title: title.trim(),
      description: description.trim(),
      priority,
      isAiGenerated
    });

    setTitle('');
    setDescription('');
    setPriority('medium');
    setIsAiGenerated(false);
    setAiMessage(null);
  };

  return (
    <form className="card" onSubmit={handleSubmit}>
      <h3 style={{ marginTop: 0 }}>Create Task with AI Assistance</h3>

      <div className="form-group">
        <label htmlFor="task-title">Task Title *</label>
        <div style={{ display: 'flex', gap: '0.75rem', alignItems: 'stretch' }}>
          <input
            id="task-title"
            type="text"
            placeholder="e.g., Optimize MongoDB queries using compound indexing"
            value={title}
            onChange={(e) => setTitle(e.target.value)}
            required
            style={{ flex: 1 }}
          />
          <button
            type="button"
            className="btn-ai"
            onClick={handleGenerateAi}
            disabled={aiLoading || !title.trim()}
            title="Generate description using backend AI API"
          >
            {aiLoading ? '✨ Thinking...' : '✨ Auto-Describe'}
          </button>
        </div>
      </div>

      {aiMessage && (
        <div className={aiMessage.type === 'success' ? 'ai-disclaimer' : 'ai-fallback-alert'}>
          {aiMessage.text}
        </div>
      )}

      <div className="form-group" style={{ marginTop: '1rem' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '0.4rem' }}>
          <label htmlFor="task-desc" style={{ margin: 0 }}>Task Description (Editable Suggestion)</label>
          {isAiGenerated && (
            <span style={{ fontSize: '0.75rem', color: 'var(--ai-glow)' }}>
              🤖 Generated by AI
            </span>
          )}
        </div>
        <textarea
          id="task-desc"
          rows="3"
          placeholder="Enter task details manually or click 'Auto-Describe' above..."
          value={description}
          onChange={(e) => setDescription(e.target.value)}
        />
      </div>

      <div className="form-group">
        <label htmlFor="task-priority">Priority</label>
        <select
          id="task-priority"
          value={priority}
          onChange={(e) => setPriority(e.target.value)}
        >
          <option value="low">Low Priority</option>
          <option value="medium">Medium Priority</option>
          <option value="high">High Priority</option>
        </select>
      </div>

      <button type="submit" className="btn btn-primary" disabled={loading}>
        {loading ? 'Saving Task...' : 'Save Task to Database'}
      </button>
    </form>
  );
}
